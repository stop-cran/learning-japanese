"""Generate B171 stroke files from parent-verified KanjiVG inputs; checks generator/variant identity on the actual base."""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

WT = Path(r"C:\Users\romanko\n1-kanji-workspace\b171-wt")
BASE = "beca991c03d66578b2abccce7f29de1c4a2ab983"
CACHE = Path(r"C:\Users\romanko\.copilot\session-state\60266d87-4e3d-4c12-86b1-ef1e81f912a4\files\stroke-inputs-70a0b7ae0c18")
OUT = Path(__file__).with_name("b171_strokes.json")
MEMBERS = "戒戯扉扶抄把抑披抹露"


def git(*a):
    return subprocess.check_output(["git", "-C", str(WT), *a]).decode().strip()


def main():
    receipt = json.loads((CACHE / "receipt.json").read_text(encoding="utf-8"))
    if git("rev-parse", BASE + ":tools/generate_strokes.py") != receipt["generatorGitBlob"]:
        raise SystemExit("generator changed since cache")
    if git("rev-parse", BASE + ":tools/order_variants.json") != receipt["variantsGitBlob"]:
        raise SystemExit("variants changed since cache")
    sys.path.insert(0, str(WT / "tools"))
    import generate_strokes as gs
    if gs.KANJIVG_REVISION != receipt["revision"]:
        raise SystemExit("revision pin differs")
    variants = json.loads((WT / "tools" / "order_variants.json").read_text(encoding="utf-8"))
    index = {r["kanji"]: r for r in json.loads((WT / "docs/n1-sources/source-index.json").read_text(encoding="utf-8"))}
    rows = {r["kanji"]: r for r in receipt["rows"]}
    out = []
    for c in MEMBERS:
        r = rows[c]
        code = f"{ord(c):05x}"
        raw = (CACHE / "svg" / (code + ".svg")).read_bytes()
        oid = hashlib.sha1(f"blob {len(raw)}\0".encode() + raw).hexdigest()
        meta = index[c]["kanjivgInventory"]
        if oid != r["svgGitBlob"] or oid != meta["sha"] or len(raw) != meta["size"]:
            raise SystemExit(f"{c}: svg identity mismatch")
        parsed = gs.convert(c, raw.decode("utf-8"))
        if c in variants:
            parsed["orderVariants"] = variants[c]
        data = (json.dumps(parsed, ensure_ascii=False, separators=(",", ":")) + "\n").encode()
        sha = hashlib.sha256(data).hexdigest()
        if data != (CACHE / "generated" / (code + ".json")).read_bytes() or sha != r["sha256"]:
            raise SystemExit(f"{c}: generated bytes differ from parent cache")
        if parsed["strokeCount"] != index[c]["metadata"]["strokes"]:
            raise SystemExit(f"{c}: stroke count {parsed['strokeCount']} != metadata")
        dest = WT / "strokes" / (c + ".json")
        if dest.exists():
            raise SystemExit(f"{c}: stroke file already exists")
        dest.write_bytes(data)
        out.append(dict(kanji=c, code=code, svgGitBlob=oid, svgBytes=len(raw), strokeCount=parsed["strokeCount"],
                        jsonSha256=sha, variant=c in variants))
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(" ".join(f"{e['kanji']}{e['strokeCount']}{'v' if e['variant'] else ''}" for e in out))


if __name__ == "__main__":
    main()

