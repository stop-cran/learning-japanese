def run(name: str, output_dir: Path, expected_manifest: str | None) -> str | None:
    if support.available_ram() <= 2 * 1024**3:
        raise MemoryError(f"{name}: startup requires more than 2048 MiB free RAM.")
    log = output_dir / f"{name}.log"
    receipt = output_dir / f"{name}.json"
    if log.exists() or receipt.exists():
        raise FileExistsError(f"Preserve an existing gate run before a deliberate rerun: {name}")
    guard = support.RamGuard()
    guard.start()
    process = None
    started = datetime.now(timezone.utc).isoformat()
    env = {
        **os.environ,
        "N1_REPO": str(REPO),
        "PYTHONPATH": os.pathsep.join(item for item in (str(LEAN), os.environ.get("PYTHONPATH", "")) if item),
        "PYTHONIOENCODING": "utf-8",
        "PYTHONDONTWRITEBYTECODE": "1",
    }
    command = [sys.executable, "-B", *map(str, checks[name])]
    try:
        with log.open("xb") as stream:
            process = subprocess.Popen(command, cwd=REPO, stdout=stream, stderr=subprocess.STDOUT, env=env)
            code = process.wait()
            guard.check()
    finally:
        if process is not None and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()
        memory = guard.finish()
    memory["peakScope"] = "B120 gate launcher and monitor thread; not child process peaks."
    memory["additionalChecks"] = "Fresh >2048 MiB admission; continuous 0.25-second global RAM sampling; abort below 1024 MiB."
    data = log.read_bytes()
    result = {
        "gate": name, "startedAt": started, "completedAt": datetime.now(timezone.utc).isoformat(),
        "command": command, "cwd": str(REPO), "exitCode": code,
        "logSha256": hashlib.sha256(data).hexdigest(), "logBytes": len(data), "memory": memory,
    }
    manifest_sha = hashlib.sha256((REPO / "manifest.json").read_bytes()).hexdigest() if name in ("manifest", "manifest-rebuild") else None
    result["manifestSha256"] = manifest_sha
    result["manifestReproducible"] = name == "manifest-rebuild" and manifest_sha == expected_manifest
    result["expectedManifestSha256"] = expected_manifest if name == "manifest-rebuild" else None
    receipt.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False), flush=True)
    print(data.decode("utf-8"), end="", flush=True)
    if memory["breach"] or code:
        raise RuntimeError(f"B120 gate failed: {name}; see preserved log and receipt.")
    if name == "manifest-rebuild" and manifest_sha != expected_manifest:
        raise ValueError(f"Manifest rebuild changed generated bytes: {expected_manifest} != {manifest_sha}")
    return manifest_sha if name == "manifest" else expected_manifest


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: python run-committed-revision-checks.py <new-gate-results-directory>")
    if subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO).decode().strip() != START_HEAD:
        raise RuntimeError("The coordinator rerun is pinned to the committed B120 reconciliation HEAD.")
    if subprocess.check_output(["git", "rev-parse", "HEAD^@"], cwd=REPO).decode().split() != [PARENT]:
        raise RuntimeError("Reconciliation HEAD must be the sole direct child of the initial candidate.")
    if subprocess.check_output(["git", "status", "--porcelain=v1", "--untracked-files=all"], cwd=REPO).strip():
        raise RuntimeError("Worktree must be clean before the coordinator rerun.")
    if hashlib.sha256((REPO / "manifest.json").read_bytes()).hexdigest() != COMMITTED_MANIFEST:
        raise RuntimeError("Committed manifest bytes differ from the author handoff.")
    output_dir = Path(sys.argv[1]).resolve()
    if output_dir.parent != HERE or output_dir.exists():
        raise ValueError("Output must be a new direct subdirectory of scratch-120.")
    output_dir.mkdir(parents=True, exist_ok=False)
    manifest_sha = None
    for name in checks:
        manifest_sha = run(name, output_dir, manifest_sha)
    summary = {
        "batch": "120", "status": "PASS", "base": BASE, "startingHead": START_HEAD, "checks": list(checks),
        "manifestSha256": manifest_sha, "manifestReproducible": True,
        "readingAudit": {"wrapper": "scratch-120/check-reading-exposure.py", "supplementalReadings": "逮=だい,てい,およぶ", "targetedPool": "Starter+逮+each supplemental-reading holder"},
        "limits": "Host content gates and bounded Python reading-pool model only; no arbitrary-pool, multiple-borrow, Kotlin/native/device, or publication acceptance.",
    }
    if subprocess.check_output(["git", "status", "--porcelain=v1", "--untracked-files=all"], cwd=REPO).strip():
        raise RuntimeError("Gates changed tracked or untracked repository files.")
    if manifest_sha != COMMITTED_MANIFEST:
        raise RuntimeError("Gate-built manifest differs from the committed manifest.")
    summary["parent"] = PARENT
    summary["cleanBeforeAndAfter"] = True
    (output_dir / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for path in output_dir.iterdir():
        if path.is_file():
            path.chmod(stat.S_IREAD)
    print(json.dumps(summary, ensure_ascii=False))


if __name__ == "__main__":
    main()
