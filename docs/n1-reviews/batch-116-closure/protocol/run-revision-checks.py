"""Run the existing content gates into a new directory without overwriting frozen logs."""
import argparse
import hashlib
import importlib.util
import json
import stat
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNNER = HERE / "run-checks.py"
RUNNER_SHA = "5e45c2d6aab85a36842d1b2a907fc6ef74662a8e968fb55bc72b105e7ff6df86"
CHECKS = (
    "lint", "quiz-safety", "linkplan", "reading-exposure-final",
    "validate", "manifest", "unittest", "budget", "vocabulary", "manifest-rebuild",
)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="New gate-results directory under scratch-116")
    args = parser.parse_args()
    output = args.output.resolve()
    if output.parent != HERE or output.exists():
        raise ValueError("Output must be a new direct subdirectory of scratch-116")
    if hashlib.sha256(RUNNER.read_bytes()).hexdigest() != RUNNER_SHA:
        raise ValueError("Original gate runner changed")
    spec = importlib.util.spec_from_file_location("b116_existing_gates", RUNNER)
    runner = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(runner)
    output.mkdir()
    runner.HERE = output
    manifest_sha = None
    for name in CHECKS:
        runner.run(name)
        if name in ("manifest", "manifest-rebuild"):
            current = hashlib.sha256((runner.REPO / "manifest.json").read_bytes()).hexdigest()
            if name == "manifest":
                manifest_sha = current
            elif current != manifest_sha:
                raise ValueError("Manifest rebuild changed the generated bytes")
    result = {
        "status": "PASS",
        "runnerSha256": RUNNER_SHA,
        "checks": list(CHECKS),
        "manifestReproducible": True,
        "manifestSha256": manifest_sha,
        "limits": "Host content gates only; not linguistic, native, or device acceptance.",
    }
    receipt = output / "summary.json"
    with receipt.open("x", encoding="utf-8") as stream:
        stream.write(json.dumps(result, indent=2) + "\n")
    for path in output.iterdir():
        if path.is_file():
            path.chmod(stat.S_IREAD)
    print(json.dumps(result))


if __name__ == "__main__":
    main()
