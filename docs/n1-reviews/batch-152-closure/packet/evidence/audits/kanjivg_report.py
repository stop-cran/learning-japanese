"""Build the KanjiVG evidence files for the B152 review packet from the pinned SVGs in this folder."""
import os, hashlib, xml.etree.ElementTree as ET
D = os.path.dirname(os.path.abspath(__file__))
REV = '70a0b7ae0c18ceb5cb358274b029cce0234a43bc'
NS = '{http://kanjivg.tagaini.net}'
SVG = '{http://www.w3.org/2000/svg}'
K = '趣 跳 踏 躍 較 載 輝 輩 迫 逸 遂 遣 避 郡 郷'.split()
def walk(g, d, lines):
    el = g.get(NS + 'element')
    nums = [int(p.get('id').split('-s')[-1]) for p in g.iter(SVG + 'path')]
    rng = '%d-%d (%d)' % (min(nums), max(nums), len(nums)) if nums else ''
    attrs = ' '.join('%s=%s' % (k, v) for k, v in [('position', g.get(NS + 'position')), ('part', g.get(NS + 'part')),
                     ('radical', g.get(NS + 'radical')), ('original', g.get(NS + 'original')), ('phon', g.get(NS + 'phon'))] if v)
    if el or d == 0:
        lines.append('  ' * d + '%s %s strokes %s' % (el or '?', attrs, rng))
    for c in g:
        if c.tag == SVG + 'g':
            walk(c, d + 1 if el else d, lines)
comp, raws = [], []
comp.append('KanjiVG component groups and stroke types at revision %s, generated by kanjivg_report.py from the raw SVG files in kanjivg-svgs.txt.' % REV)
comp.append('Each tree line: element, KanjiVG attributes, and the stroke numbers the group covers. Strokes outside any element group are listed only in the stroke list.')
comp.append('KanjiVG attributes such as phon= and radical= are KanjiVG annotations; the cards make no claim based on them.\n')
for k in K:
    h = '%05x' % ord(k)
    raw = open(os.path.join(D, h + '.svg'), 'rb').read()
    url = 'https://raw.githubusercontent.com/KanjiVG/kanjivg/%s/kanji/%s.svg' % (REV, h)
    root = ET.fromstring(raw)
    g = [x for x in root.iter(SVG + 'g') if x.get('id') == 'kvg:' + h][0]
    lines = []; walk(g, 0, lines)
    strokes = [p for p in root.iter(SVG + 'path') if p.get('id', '').startswith('kvg:%s-s' % h)]
    comp.append('== %s (%s) %s\n   sha256 %s' % (k, h, url, hashlib.sha256(raw).hexdigest()))
    comp += ['   ' + x for x in lines]
    comp.append('   stroke types: ' + ' '.join('%s:%s' % (p.get('id').split('-s')[-1], p.get(NS + 'type')) for p in strokes))
    comp.append('')
    raws.append('===== %s %s sha256 %s =====\n%s\n' % (k, url, hashlib.sha256(raw).hexdigest(), raw.decode('utf-8')))
open(os.path.join(D, 'kanjivg-components.txt'), 'w', encoding='utf-8', newline='\n').write('\n'.join(comp))
open(os.path.join(D, 'kanjivg-svgs.txt'), 'w', encoding='utf-8', newline='\n').write('\n'.join(raws))
print(len(K), 'kanji')
